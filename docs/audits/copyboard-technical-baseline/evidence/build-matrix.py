"""Renders 03-INTERACTION-MATRIX.md from evidence/qa-results.json (Run 01).

Usage (from docs/audits/copyboard-technical-baseline/): python3 evidence/build-matrix.py
"""
import json
from collections import Counter

d = json.load(open('evidence/qa-results.json'))
R = d['results']
esc = lambda s: str(s or '').replace('|', '\\|').replace('\n', ' ')
SEV = {'Critical': 0, 'High': 1, 'Medium': 2, 'Low': 3, 'Info': 4, '—': 5}
ICON = {'PASS': '✅ PASS', 'DEFECT': '❌ DEFECT', 'OBSERVATION': 'ℹ️ OBSERVATION', 'NOT VERIFIED': '⚪ NOT VERIFIED', 'BLOCKED': '⛔ BLOCKED'}
c = Counter(r['status'] for r in R)

out = [
    "# 03 — Interaction Matrix\n",
    "This matrix records real browser interactions with the existing app, at commit `ac721fe` served locally from a static `python3 -m http.server`. "
    "Every row was produced by `evidence/qa-interactions.mjs`. The raw machine-readable output is `evidence/qa-results.json`. "
    "This file is generated by `evidence/build-matrix.py`.\n",
    "## Environment and rules\n",
    f"- **Browser.** {d['browser']}. Each scenario runs in a **fresh, isolated browser context** (empty profile) with locale `de-DE` and time zone Europe/Berlin.",
    "- **Viewports.** Desktop 1440×900. Mobile 390×844 (touch + mobile emulation, DPR 2). Tablet 820×1180, screenshots only.",
    "- **Data.** Disposable synthetic data only: generated PNGs, dummy texts, a fake PDF and CSV, and one PIN-locked dummy entry (PIN `1234`, test-only).",
    "- **Network.** All external requests were intercepted:",
    "  - JSZip 3.10.1 was served from a local npm copy.",
    "  - The Supabase client was **replaced by an in-memory mock** for the `I‑C0x` rows, and blocked otherwise.",
    "  - Tesseract was stubbed for I‑43 and blocked otherwise.",
    "  - Fonts were blocked.",
    f"  - External hosts requested (all intercepted): `{', '.join(d['externalHostsRequested'])}`. **No request reached `*.supabase.co` or any production resource.**",
    f"- **Generated at.** {d['generatedAt']}. I‑19 was re-run 3× afterwards and reclassified; see its row.",
    f"- **Totals.** {len(R)} scenarios: **{c['DEFECT']} DEFECT**, {c['PASS']} PASS, {c['OBSERVATION']} OBSERVATION, {c['NOT VERIFIED']} NOT VERIFIED, {c.get('BLOCKED', 0)} BLOCKED.\n",
    "**Status meaning.**",
    "- PASS: behavior matched the expectation.",
    "- DEFECT: reproduced deviation from the app's own labels, comments or evident intent.",
    "- OBSERVATION: works as coded (or is intermittent and not confirmed), but noteworthy for the refresh.",
    "- NOT VERIFIED: requires capabilities that were unavailable.\n",
    "**Severity.**",
    "- Critical: data loss without user action.",
    "- High: data loss, security impact, or a core flow broken.",
    "- Medium: functional defect with a workaround.",
    "- Low: cosmetic or edge case.\n",
    "**Synthetic events.** Paste is dispatched as a `ClipboardEvent`; touch uses CDP emulation. "
    "They are close to, but not identical with, real user input. Where this matters, the row's note says so.\n",
    "Reproduce:\n",
    "```bash\npython3 -m http.server 8765 --bind 127.0.0.1   # repo root\n"
    "PLAYWRIGHT_PATH=<path to playwright> JSZIP_PATH=<path to jszip.min.js> \\\n"
    "  node docs/audits/copyboard-technical-baseline/evidence/qa-interactions.mjs [id-regex]\n```\n",
    "## A. Defects ranked by severity\n",
    "| Sev | ID | Area | Interaction → observed |\n|---|---|---|---|",
]
for r in sorted([r for r in R if r['status'] == 'DEFECT'], key=lambda r: (SEV.get(r['severity'], 9), r['id'])):
    o = esc(r['observed'])
    out.append(f"| {r['severity']} | {r['id']} | {esc(r['area'])} | {esc(r['action'])} → {o[:260]}{'…' if len(o) > 260 else ''} |")

out.append("\n## B. Full matrix\n")
groups = [
    ('Capture and clipboard', ('I-01', 'I-02', 'I-03', 'I-04', 'I-05', 'I-06')),
    ('Cards, menus and editing', ('I-07', 'I-08', 'I-09', 'I-10', 'I-46', 'I-11', 'I-12', 'I-13', 'I-41', 'I-44')),
    ('Undo / Redo', ('I-14', 'I-15', 'I-16', 'I-17', 'I-18')),
    ('Drag & drop, selection, folders', ('I-19', 'I-20', 'I-21', 'I-22', 'I-23', 'I-24', 'I-25')),
    ('Spaces, search, modals, settings', ('I-28', 'I-29', 'I-38', 'I-39', 'I-40', 'I-45')),
    ('Protection features', ('I-26', 'I-27')),
    ('Security (rendering / import)', ('I-31', 'I-32', 'I-33', 'I-33b')),
    ('Persistence and backup', ('I-34', 'I-35', 'I-36', 'I-37')),
    ('Media and OCR', ('I-42', 'I-43')),
    ('Accessibility and visual', ('I-30', 'I-V01')),
    ('Mobile / touch', ('I-M01', 'I-M02', 'I-M03', 'I-M04', 'I-M05')),
    ('Cloud (sandbox + mock backend)', ('I-C01', 'I-C02', 'I-C03', 'I-C04', 'I-C05')),
]
by_id = {r['id']: r for r in R}
used = set()
for title, ids in groups:
    out.append(f"### {title}\n")
    out.append("| ID | Action | Expected | Observed | Status | Severity |\n|---|---|---|---|---|---|")
    for i in ids:
        r = by_id[i]; used.add(i)
        obs = esc(r['observed'])
        if r.get('note'):
            obs += f" <br>*Note: {esc(r['note'])}*"
        out.append(f"| {r['id']} | {esc(r['action'])} | {esc(r['expected'])} | {obs} | {ICON.get(r['status'], r['status'])} | {r['severity']} |")
    out.append("")
missing = [r['id'] for r in R if r['id'] not in used]
assert not missing, missing

out += [
    "## C. Interactions covered only by code review or screenshots\n",
    "| Interaction | Expected | Finding | Basis |\n|---|---|---|---|",
    "| Space-bar quick look on a hovered folder | Opens the folder | `openFolder(hoveredCardItem)` (`app.js:4559`) | Code |",
    "| Selection-bar \"Verschieben\" to a *new* space | Creates the space and moves the selection in one undo step | `createSpaceQuiet` + `moveItemToSpace` under one `crossSpace` checkpoint (`app.js:3284`) | Code |",
    "| Color picker opened from the overflow dropdown | Dropdown stays open after picking | Explicit re-open logic (`app.js:4362`) | Code |",
    "| Help → Speicher → \"Öffnen\" | Storage manager stacks above help | Screenshot desktop‑23 and I‑40 | Browser |",
    "| Text-modal \"Abbrechen\" after \"Inhalt bearbeiten\" | Edit context reset | Reset in the cancel handler and in the modal-stack close (`app.js:4617`, `5006`) | Code |",
    "| Burn link overlay | Only \"Gelesen — schließen\" closes it | Registered with `escape:false, backdrop:false` (`app.js:5033`) | Code |",
    "| Lowering the recent-history limit | History truncated immediately | `helpRecentLimitSelect` handler (`app.js:2822`) | Code |",
    "| Drag-in of text/URL from another app | Becomes a text card | `drop` → `text/uri-list` or `text/plain` (`app.js:3697`) | Code |",
    "| Many spaces / narrow window | Overflow arrows and dropdown | Screenshots desktop‑32/33, mobile‑02 | Browser (visual) |",
    "| Edit from a PIN-bypassed (empty) preview → \"Inhalt bearbeiten\" → save | Should be impossible | Would write plaintext into `data` while `locked`/`encData` remain (`app.js:3604`, `4598`) | Code (not executed) |",
    "",
]
open('03-INTERACTION-MATRIX.md', 'w').write("\n".join(out))
print('rows', len(R), dict(c))
